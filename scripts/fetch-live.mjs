// Builds js/live.js: which channels in scripts/live.json are streaming live right now.
// youtube.com/channel/<id>/live points at the channel's current broadcast when there is one.
// Only streams that are live now and allow embedding are kept.
// Usage: node scripts/fetch-live.mjs
import {readFile, writeFile} from "node:fs/promises";
import {roman} from "./roman.mjs";

const ROOT = new URL("..", import.meta.url);
const {groups} = JSON.parse(await readFile(new URL("scripts/live.json", ROOT), "utf8"));
const HEADERS = {"accept-language": "en-IN,en;q=0.9", cookie: "SOCS=CAI; CONSENT=YES+1",
  "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"};

async function liveNow(channelId) {
  const r = await fetch("https://www.youtube.com/channel/" + channelId + "/live", {headers: HEADERS});
  const html = await r.text();
  const m = html.match(/ytInitialPlayerResponse\s*=\s*(\{.+?\});(?:var |<\/script>)/s);
  if (!m) return null; // no player on the page: not live
  const p = JSON.parse(m[1]), v = p.videoDetails || {}, ps = p.playabilityStatus || {};
  if (!v.isLive || ps.status !== "OK" || ps.playableInEmbed !== true) return null;
  return {id: v.videoId, t: roman(v.title).replace(/#\S+/g, "").replace(/\s+/g, " ").trim().slice(0, 90)};
}

const LIVE = {}, report = [];
for (const [group, list] of Object.entries(groups)) {
  LIVE[group] = [];
  for (const s of list) {
    const hit = await liveNow(s.id).catch(e => (report.push(`error ${s.src}: ${e.message}`), null));
    if (hit) LIVE[group].push({...hit, src: s.src, lang: s.lang});
    await new Promise(r => setTimeout(r, 300));
  }
  report.push(`${group}: ${LIVE[group].map(x => x.src).join(", ") || "nothing live"}`);
}

// Stable output (no timestamp) so the file only changes when what's live changes
await writeFile(new URL("js/live.js", ROOT),
  "/* Generated by scripts/fetch-live.mjs from scripts/live.json. Do not edit by hand. */\nconst LIVE = "
  + JSON.stringify(LIVE, null, 1) + ";\n");
console.log(report.join("\n"));
