// js/feeds.js, split for the page (js/data.js fetches it a category at a time): js/c/<category>.js, one file per category
// with its videos as in js/feeds.js, and js/feedmap.js listing the files in js/feeds.js's order, each with a stamp from
// its contents (a category that didn't change keeps its stamp, so browsers keep their copy). scripts/build-pages.mjs
// writes them; scripts/check.mjs makes sure the files on disk are these.
// js/feeds.js must be grouped by category (scripts/fetch-feeds.mjs writes it so): the page puts the categories back
// together in that order, so the catalogue it builds is exactly the one built from js/feeds.js.
import {createHash} from "node:crypto";

export const sha = s => createHash("sha1").update(s).digest("hex").slice(0, 10);

export function splitFeeds(FEED, refused = "") {
  const cats = new Map(); let last = null;
  for (const v of FEED) {
    if (v.cat !== last && cats.has(v.cat)) throw new Error(`js/feeds.js isn't grouped by category ("${v.cat}" comes back after others): run scripts/fetch-feeds.mjs`);
    if (!cats.has(v.cat)) cats.set(v.cat, []); cats.get(v.cat).push(v); last = v.cat;
  }
  const lower = new Set();
  for (const c of cats.keys()) { // a file name on every system (and no two that differ only in case)
    if (!/^[a-z0-9][a-z0-9-]*$/.test(c) || lower.has(c.toLowerCase())) throw new Error(`category "${c}" can't be a file name in js/c/`);
    lower.add(c.toLowerCase());
  }
  const files = new Map(), list = [];
  for (const [c, items] of cats) {
    const lines = items.map(v => JSON.stringify(v)).join(",\n"), stamp = sha(lines);
    files.set(`js/c/${c}.js`, `/* Generated by scripts/build-pages.mjs from js/feeds.js: the videos of one category, which js/data.js puts in. Do not edit by hand. */\nOGTV_DATA.put(${JSON.stringify(c)},${JSON.stringify(stamp)},[\n${lines}\n]);\n`);
    list.push([c, stamp, items.length]);
  }
  const mapSrc = `/* Generated by scripts/build-pages.mjs from js/feeds.js: its categories in its order, each a file in js/c/ with its stamp and its
   number of videos (js/data.js fetches them), and the videos viewers were refused (never scheduled). Do not edit by hand. */
const FEED_MAP = ${JSON.stringify({files: list, count: FEED.length, refused})};
const REFUSED = FEED_MAP.refused;
`;
  files.set("js/feedmap.js", mapSrc);
  return {files, list, stamps: new Map(list.map(([c, s]) => [c, s])), mapStamp: sha(mapSrc)};
}
