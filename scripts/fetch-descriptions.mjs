// Writes desc/<id>.json for the programme guide: the YouTube channel that uploaded each video ("a") and its description
// ("d"), cleaned up: links, hashtags, chapter times, subscribe/social/sponsor lines and emoji go, Hindi in Devanagari is
// written in Roman letters, and lines in other scripts are left out, so everything stays in Latin script. At most ~600
// characters. The page fetches a file only when it shows that video.
// The videos on air soonest go first; ones already done are skipped, and files for videos no longer on any channel go.
// Uses the YouTube Data API when YT_API_KEY is set (50 videos a request, no cap); otherwise reads watch pages, at most
// [max] a run (default 800). YouTube starts refusing watch pages (HTTP 429) after a couple of hundred in a few minutes,
// so without a key the catalogue (~15,000 videos) fills in slowly over many nights; with a key it takes one run.
// Usage: node scripts/fetch-descriptions.mjs [max]
import {readFile, writeFile, mkdir, readdir, rm} from "node:fs/promises";
import {roman} from "./roman.mjs";

const ROOT = new URL("..", import.meta.url), DIR = new URL("desc/", ROOT);
const KEY = process.env.YT_API_KEY, MAX = +process.argv[2] || 800;
const HEADERS = {"accept-language": "en-IN,en;q=0.9", cookie: "SOCS=CAI; CONSENT=YES+1",
  "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"};
const sleep = ms => new Promise(r => setTimeout(r, ms));
const read = p => readFile(new URL(p, ROOT), "utf8");

// The site's own scripts, as check.mjs loads them, to know which videos are on air soonest
const S = new Function((await Promise.all(["catalog", "feeds", "live", "festivals", "channels", "scheduler"].map(f => read(`js/${f}.js`)))).join("\n")
  + ";return {CATALOG, CHANNELS, slotsBetween, HOUR};")();
const now = Date.now(), soon = new Map();
for (const c of S.CHANNELS) for (const s of S.slotsBetween(c, now, now + 36 * S.HOUR))
  if (!s.live && !(soon.get(s.v.id) <= s.start)) soon.set(s.v.id, s.start);
const all = [...new Set(S.CATALOG.map(v => v.id))], inCatalog = new Set(all);
const order = [...[...soon].sort((x, y) => x[1] - y[1]).map(x => x[0]), ...all.filter(id => !soon.has(id))];

await mkdir(DIR, {recursive: true});
const have = new Set((await readdir(DIR)).filter(f => f.endsWith(".json")).map(f => f.slice(0, -5)));
let removed = 0;
for (const id of have) if (!inCatalog.has(id)) { await rm(new URL(id + ".json", DIR)); have.delete(id); removed++; }
const todo = order.filter(id => !have.has(id));

// Lines that are about the uploader's business rather than the programme
const JUNK = /\b(subscrib\w*|follow|provided to youtube|auto-generated by youtube|lyrics below|like,? (share|comment)|share (this|with)|instagram|facebook|twitter|telegram|whatsapp|snapchat|threads|linkedin|patreon|discord|download|merch\w*|sponsor\w*|promo ?code|use (my |the )?code|coupon|affiliate|discount|download (the|our|now)|app (link|download)|bet|betting|casino|copyright\w*|all rights reserved|disclaimer|fair use|business (enquir|inquir)\w*|for (business|collaborations?|enquiries)|contact (us|me)|e-?mail (us|me)|join (this|our|the) channel|membership|click (here|the link|below)|link in (the )?(bio|description)|playlists?|watch (more|next|the full)|bell icon|hit the bell|notifications?)\b/i;
// A heading left with nothing under it ("VIDEO INTRODUCTION:", "Credits:") goes too
const dangling = d => { const ls = d.split("\n"); while (ls.length && /:$/.test(ls[ls.length - 1])) ls.pop(); return ls.join("\n"); };
function clean(text) {
  const lines = [];
  for (const raw of String(text || "").replace(/\r/g, "").split("\n")) {
    let l = roman(raw).replace(/https?:\/\/\S+|www\.\S+|\S+@\S+\.\S+|[#@][\p{L}\p{N}_]+/gu, "") // links, emails, hashtags, handles
      .replace(/[\p{So}\p{Cs}\p{Co}\p{Cn}‍️]/gu, "").replace(/[<>]/g, "").replace(/\s+/g, " ").trim();
    const letters = (l.match(/\p{L}/gu) || []).length, latin = (l.match(/\p{Script=Latin}/gu) || []).length;
    if (!/[A-Za-z]{2}/.test(l) || latin < letters * 0.8 || JUNK.test(l) || /^[(\[]?\d{1,2}:\d{2}/.test(l)) continue; // other scripts, boilerplate, chapter times
    if (/https?:\/\/|www\./.test(raw) && l.length < 80) continue; // "Get the book here:" once its link is gone
    lines.push(l.replace(/(?![\p{Script=Latin}])\p{L}/gu, "").replace(/^[\p{S}\p{Pd}*•·]+\s*/u, "• ").replace(/\s+/g, " ").trim()); // any bullet becomes •
  }
  let out = "";
  for (const l of lines.slice(0, 8)) {
    if (out.length + l.length + 1 <= 600) { out += (out ? "\n" : "") + l; continue; }
    if (!out) out = l.slice(0, 597).replace(/\s+\S*$/, "") + "…"; // one long paragraph: cut at a word
    break;
  }
  return dangling(out);
}
const channelName = a => { const r = roman(String(a || "")).replace(/[<>]/g, "").trim(); return /[^\p{Script=Latin}\p{N}\p{P}\p{Zs}\p{S}]/u.test(r) ? "" : r; };

async function fromApi(ids) {
  const url = "https://www.googleapis.com/youtube/v3/videos?part=snippet&key=" + KEY + "&id=" + ids.join(",");
  const r = await fetch(url); if (!r.ok) throw new Error("API " + r.status);
  return Object.fromEntries(((await r.json()).items || []).map(it => [it.id, {a: it.snippet.channelTitle, d: it.snippet.description}]));
}
async function fromPage(id) {
  const r = await fetch("https://www.youtube.com/watch?v=" + id, {headers: HEADERS});
  if (r.status === 429) throw Object.assign(new Error("HTTP 429"), {limited: true});
  if (!r.ok) throw new Error("HTTP " + r.status);
  const m = (await r.text()).match(/ytInitialPlayerResponse\s*=\s*(\{.+?\});(?:var |<\/script>)/s);
  if (!m) throw new Error("no player data");
  const v = JSON.parse(m[1]).videoDetails || {};
  return {a: v.author, d: v.shortDescription};
}
const save = (id, x) => writeFile(new URL(id + ".json", DIR), JSON.stringify({a: channelName(x.a), d: clean(x.d)}) + "\n");

let done = 0, failed = 0;
if (KEY) {
  for (let i = 0; i < todo.length; i += 50) {
    const ids = todo.slice(i, i + 50), got = await fromApi(ids);
    for (const id of ids) if (got[id]) { await save(id, got[id]); done++; } else failed++; // a video the API doesn't return is gone or private
  }
} else {
  const batch = todo.slice(0, MAX); let next = 0, limited = 0;
  await Promise.all(Array.from({length: 2}, async () => { // two at a time, gently: YouTube answers 429 to a rush
    while (next < batch.length && limited < 3) {
      const id = batch[next++];
      try { await save(id, await fromPage(id)); done++; limited = 0; }
      catch (e) { failed++; if (e.limited) limited++; }
      await sleep(800);
    }
  }));
  if (limited >= 3) console.log("YouTube is rate-limiting: stopped early; the rest come next run");
}
console.log(`${done} descriptions written, ${failed} failed, ${removed} removed; ${todo.length - done - failed > 0 ? todo.length - done - failed : 0} still to do of ${all.length}`);
